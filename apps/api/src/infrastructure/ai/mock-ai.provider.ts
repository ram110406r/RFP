import { Injectable } from "@nestjs/common";
import type {
  AiProvider,
  CompletionRequest,
  CompletionResponse,
  EmbeddingRequest,
  EmbeddingResponse,
} from "@rfp-os/ai";

import {
  GROUNDED_ANALYSIS_MODEL,
  GROUNDED_ANSWER_MODEL,
  GROUNDED_CLARIFICATION_MODEL,
  GROUNDED_IMPROVE_MODEL,
  GROUNDED_REQUIREMENT_ANALYSIS_MODEL,
  GROUNDED_TENDER_BRIEF_MODEL,
} from "./ai.constants";

@Injectable()
export class MockAiProvider implements AiProvider {
  readonly name = "mock";

  async complete(request: CompletionRequest): Promise<CompletionResponse> {
    return {
      content: JSON.stringify(mockContent(request)),
      model: request.model,
      usage: { inputTokens: 0, outputTokens: 0 },
    };
  }

  async embed(request: EmbeddingRequest): Promise<EmbeddingResponse> {
    return {
      model: request.model,
      embeddings: request.input.map((value) => deterministicEmbedding(value)),
    };
  }
}

function mockContent(request: CompletionRequest) {
  const text = request.messages.map((message) => message.content).join("\n");
  const evidenceIds = [...text.matchAll(/"evidenceId"\s*:\s*"([^"]+)"/g)].map((match) => match[1]!).slice(0, 3);

  if (request.model === GROUNDED_ANSWER_MODEL || request.model === GROUNDED_IMPROVE_MODEL) {
    return {
      answer:
        "TENDYY local mock answer: based on the configured development evidence, the platform supports the requested capability. Replace AI_PROVIDER with a real provider for production-quality drafting.",
      confidence: evidenceIds.length ? 0.78 : 0.25,
      evidenceIds,
      risk: evidenceIds.length ? "LOW" : "HIGH",
      status: evidenceIds.length ? "AI_DRAFT" : "INSUFFICIENT_EVIDENCE",
      changes: request.model === GROUNDED_IMPROVE_MODEL ? ["Applied deterministic local improvement."] : undefined,
      warnings: ["Generated by local mock AI provider."],
      metadata: { provider: "mock", local: true },
    };
  }

  if (request.model === GROUNDED_ANALYSIS_MODEL) {
    return {
      coverage: evidenceIds.length ? 1 : 0,
      supportedClaims: evidenceIds.length,
      unsupportedClaims: 0,
      contradictions: [],
      missingEvidence: evidenceIds.length ? [] : ["No local evidence was provided."],
      risk: evidenceIds.length ? "LOW" : "HIGH",
      readiness: evidenceIds.length ? "READY" : "INSUFFICIENT_EVIDENCE",
      warnings: ["Generated by local mock AI provider."],
      claims: evidenceIds.map((id) => ({ claim: `Evidence ${id} supports the draft.`, evidenceIds: [id], supported: true, reason: "Local mock evidence match." })),
      metadata: { provider: "mock", local: true },
    };
  }

  if (request.model === GROUNDED_TENDER_BRIEF_MODEL) {
    return {
      overview: "Local mock tender brief for development workflow testing.",
      keyRequirements: ["Review mandatory requirements", "Attach evidence", "Complete approvals"],
      questions: [],
      documents: [],
      dates: [],
      risks: [],
      missingInformation: [],
      clarifications: [],
      metadata: { provider: "mock", local: true },
    };
  }

  if (request.model === GROUNDED_REQUIREMENT_ANALYSIS_MODEL) {
    return {
      category: "General",
      summary: "Local mock requirement analysis.",
      questionClassification: "RFP_REQUIREMENT",
      missingInformation: [],
      readiness: evidenceIds.length ? "READY" : "NEEDS_REVIEW",
      risk: evidenceIds.length ? "LOW" : "MEDIUM",
      warnings: ["Generated by local mock AI provider."],
      metadata: { provider: "mock", local: true },
    };
  }

  if (request.model === GROUNDED_CLARIFICATION_MODEL) {
    return {
      readiness: "NEEDS_REVIEW",
      risk: "MEDIUM",
      suggestions: [{ question: "Please confirm the missing requirement detail.", reason: "Local mock clarification." }],
      missingInformation: [],
      metadata: { provider: "mock", local: true },
    };
  }

  return { metadata: { provider: "mock", local: true } };
}

function deterministicEmbedding(value: string) {
  let hash = 0;
  for (const char of value) hash = (hash * 31 + char.charCodeAt(0)) >>> 0;
  return Array.from({ length: 8 }, (_, index) => ((hash + index * 97) % 1000) / 1000);
}
